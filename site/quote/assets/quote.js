  const mockSave = db => { try { localStorage.setItem(MOCK_KEY, JSON.stringify(db)); } catch (e) { /* storage blocked */ } };
  let QV = null, PB = null;
  async function mockDeps() {
    if (!QV) { QV = await import('/assets/quote_view.mjs'); PB = await getJson('/assets/pricebook.json'); }
  }
  const mockId = () => (window.crypto && crypto.randomUUID) ? crypto.randomUUID() : String(Date.now()) + Math.random().toString(16).slice(2);
  function mockFind(db) {
    const q = (db.quotes || []).find(x => x.public_token === token);
    if (!QV.TOKEN_RX.test(token) || !QV.isPublic(q)) throw new Error('not_found');
    return q;
  }
  const mockProfile = (db, q) => (db.profiles || []).find(p => p.id === q.user_id) || null;
  function mockEvent(db, q, type, payload) {
    (db.events = db.events || []).push({ id: mockId(), actor: 'system', entity: 'quote', entity_id: q.id, user_id: q.user_id, type,
      payload: payload || {}, client_visible: false, created_at: new Date().toISOString() });
  }
  async function mockView() {
    await mockDeps();
    const db = mockDb(), q = mockFind(db), now = new Date();
    if (['sent', 'viewed'].includes(q.status) && QV.isExpired(q, now)) q.status = 'expired';
    else if (q.status === 'sent') { q.status = 'viewed'; q.viewed_at = q.viewed_at || now.toISOString(); }
    mockSave(db);
    return QV.toPublicView(q, mockProfile(db, q), now, PB, BRAND.agreement_version, mockPays(db, q));
  }
  // ---- mock PayPal checkout: mirrors the SQL RPCs pay_target / pay_set_order / pay_record_capture / pay_use_upwork
  // (supabase/migrations/20261021100100_us_paypal_checkout.sql) on the shared mock DB, with fake PayPal ids
  const mockClient = (db, q) => (db.clients || []).filter(c => c.quote_id === q.id).sort((a, b) => String(a.created_at).localeCompare(String(b.created_at)))[0] || null;
  function mockPays(db, q) {
    const c = mockClient(db, q);
    return c ? (db.payments || []).filter(p => p.client_id === c.id) : [];
  }
  function mockOut(db, to, template, extra) {
    (db.outbox = db.outbox || []).push(Object.assign({ id: mockId(), to, template, subject: template, created_at: new Date().toISOString() }, extra || {}));
  }
  function mockDeposit(db, q) {
    if (q.status !== 'accepted') throw new Error('quote_not_accepted');
    if (q.pay_method !== PP) throw new Error('not_paypal');
    let c = mockClient(db, q);
    const now = new Date().toISOString();
    if (!c) {   // the same rows as the admin's "פתח כרטיס לקוח" (adminCreateClientFromQuote)
      const core = (q.items || []).map(i => i.code).find(x => ['RCP', 'WEB', 'BNDL'].indexOf(x) !== -1) || 'RCP';
      const prof = mockProfile(db, q) || {};
      c = { id: mockId(), user_id: q.user_id, quote_id: q.id, products: [core], status: 'onboarding', go_live_at: null, monthly_cents: q.monthly_cents,
        next_bill_on: null, ended_at: null, business_name: prof.company || null, created_at: now, updated_at: now };
      (db.clients = db.clients || []).push(c);
      db.payments = db.payments || [];
      [['deposit', q.deposit_cents || 0], ['final', (q.setup_cents || 0) - (q.deposit_cents || 0)]].forEach(([kind, amount]) =>
        db.payments.push({ id: mockId(), client_id: c.id, kind, amount_cents: amount, method: q.pay_method, status: 'due', reference: null, paid_at: null,
          provider: null, provider_order_id: null, provider_capture_id: null, payer_email: null, created_at: now, updated_at: now }));
    }
    return (db.payments || []).find(p => p.client_id === c.id && p.kind === 'deposit');
  }
  const mockPpId = p => p + mockId().replace(/[^A-Za-z0-9]/g, '').slice(0, 14).toUpperCase();
  async function mockPayCreate() {
    await mockDeps();
    const db = mockDb(), q = mockFind(db), p = mockDeposit(db, q);
    if (p.status === 'paid') throw new Error('already_paid');
    if (p.provider_capture_id) throw new Error('payment_pending');
    Object.assign(p, { provider: 'paypal', provider_order_id: mockPpId('MOCKORDER'), updated_at: new Date().toISOString() });
    mockSave(db);
    return p.provider_order_id;
  }
  async function mockPayCapture(orderId) {
    await mockDeps();
    const db = mockDb(), q = mockFind(db), p = mockDeposit(db, q), now = new Date().toISOString();
    if (p.status === 'paid') { if (p.provider_order_id === orderId) return { status: 'paid', reference: p.provider_capture_id }; throw new Error('already_paid'); }
    if (p.provider_order_id !== orderId) throw new Error('order_mismatch');
    const prof = mockProfile(db, q) || {};
    Object.assign(p, { status: 'paid', paid_at: now, updated_at: now, method: PP, provider_capture_id: mockPpId('MOCKCAP'), payer_email: prof.email || null });
    mockOut(db, prof.email || '', 'payment_receipt', { payment_id: p.id });
    mockOut(db, 'owner', 'admin_payment_received', { payment_id: p.id });
    mockOut(db, prof.email || '', 'deposit_received', { payment_id: p.id });   // trigger payments_to_outbox
    (db.events = db.events || []).push({ id: mockId(), actor: 'runtime', entity: 'payment', entity_id: p.id, user_id: q.user_id, type: 'payment_captured',
      payload: { provider: 'paypal', kind: 'deposit', amount_cents: p.amount_cents, capture_id: p.provider_capture_id }, client_visible: true, created_at: now });
    mockSave(db);
    return { status: 'paid', reference: p.provider_capture_id, amount_cents: p.amount_cents };
  }
  async function mockUseUpwork() {
    await mockDeps();
    const db = mockDb(), q = mockFind(db);
    if (q.status !== 'accepted') throw new Error('quote_not_accepted');
    if (q.pay_method !== 'upwork') {
      if (q.pay_method !== PP) throw new Error('not_paypal');
      const rows = mockPays(db, q);
      if (rows.some(p => p.kind === 'deposit' && (p.status !== 'due' || p.provider_capture_id))) throw new Error('deposit_already_paid');
      q.pay_method = 'upwork';
      rows.filter(p => p.status === 'due' && !p.provider_capture_id).forEach(p => Object.assign(p, { method: 'upwork', provider: null, provider_order_id: null }));
      mockEvent(db, q, 'pay_method_changed', { from: PP, to: 'upwork', by: 'client' });
      mockOut(db, 'owner', 'admin_upwork_requested', { quote_id: q.id });
      mockSave(db);
    }
    return QV.toPublicView(q, mockProfile(db, q), new Date(), PB, BRAND.agreement_version, mockPays(db, q));
  }
  async function mockAccept(name) {
    await mockDeps();
    const db = mockDb(), q = mockFind(db), now = new Date();
    const chk = QV.acceptCheck(q, { name, agree: true, agreement_version: Q.agreement_version }, now, BRAND.agreement_version);
    if (chk && chk.code) throw new Error(chk.code);
    if (!chk) {
      Object.assign(q, { status: 'accepted', accepted_name: QV.normName(name), accepted_at: now.toISOString(), updated_at: now.toISOString(),
        agreement_version: q.agreement_version || BRAND.agreement_version, accepted_ip: 'mock', accepted_ua: 'mock' });
      const prof = mockProfile(db, q);
      [['quote', 'accepted'], ['admin', 'quote', 'accepted']].map(p => p.join('_')).forEach(t => {   // names joined: analytics event name is a substring
        mockEvent(db, q, 'email_requested', { template: t });
        (db.outbox = db.outbox || []).push({ id: mockId(), to: t.indexOf('admin') === 0 ? 'owner' : (prof && prof.email) || '', template: t, quote_id: q.id,
          subject: t, created_at: now.toISOString() });
      });
      mockSave(db);
    }
    return QV.toPublicView(q, mockProfile(db, q), now, PB, BRAND.agreement_version, mockPays(db, q));
  }

