/* Public quote page: /quote/?t=<token>. Renders the JSON returned by the Edge Function quote-view (no sign-in) and
   accepts through quote-accept. Brand strings and prices are never typed here: brand comes from /assets/brand.json,
   every amount from the quote JSON (computed server-side from config/pricebook.json).
   Fixture mode (no network): ?t=fixture | fixture-bundle | fixture-web | fixture-accepted | fixture-expired, allowed on
   localhost or when /assets/config.js says BACKEND:'mock'. Files are generated by tools/build_quote_fixtures.ts. */
(function () {
  'use strict';
  const CFG = window.SITE_CONFIG || {};
  const $ = s => document.querySelector(s);
  const esc = s => String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const money = c => c == null ? '' : '$' + (c / 100).toLocaleString('en-US', { minimumFractionDigits: c % 100 ? 2 : 0, maximumFractionDigits: 2 });
  const fmtDate = iso => { try { return new Intl.DateTimeFormat('en-US', { month: 'long', day: 'numeric', year: 'numeric' }).format(new Date(iso)); } catch (e) { return String(iso || '').slice(0, 10); } };
  const md = s => String(s || '').split(/\n{2,}/).map(p => p.trim()).filter(Boolean)
    .map(p => '<p>' + esc(p).replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/\n/g, '<br>') + '</p>').join('');

  let BRAND = {};
  let Q = null;
  // The token is a bearer secret: read it from ?t= (email links) or #t=, then keep it only in the fragment, which browsers
  // never send to servers or in Referer. The query is removed BEFORE analytics loads; GA gets a token-free page_location.
  const QS0 = new URLSearchParams(location.search);   // read once: the query is stripped from the URL right below
  const fromHash = new URLSearchParams(location.hash.replace(/^#/, '')).get('t');
  const token = ((QS0.get('t')) || fromHash || '').trim();
  if (location.search && history.replaceState) {
    try { history.replaceState(null, '', location.pathname + (token ? '#t=' + encodeURIComponent(token) : '')); } catch (e) { /* keep going */ }
  }
  const cleanUrl = location.origin + location.pathname;
  const isLocal = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(location.hostname);
  // Mock backend = the same browser-only store the client portal and admin use (site/start/assets/mock/mock-backend.js,
  // localStorage 'aplp_mock_db_v1'); same switch rules as /start/assets/backend.js (BACKEND:'mock', or ?mock=1 on localhost).
  const ssGet = k => { try { return sessionStorage.getItem(k); } catch (e) { return null; } };
  const qsMock = QS0.get('mock');
  if (qsMock === '1' && (isLocal || CFG.ALLOW_MOCK_SWITCH)) { try { sessionStorage.setItem('start_force_mock', '1'); } catch (e) { /* blocked */ } }
  if (qsMock === '0') { try { sessionStorage.removeItem('start_force_mock'); } catch (e) { /* blocked */ } }
  const mockMode = CFG.BACKEND === 'mock' || ssGet('start_force_mock') === '1';
  const fixture = /^fixture(-[a-z]+)?$/.test(token) && (isLocal || CFG.BACKEND === 'mock');
  const fnUrl = name => (CFG.SUPABASE_URL || '').replace(/\/$/, '') + '/functions/v1/' + name;
  const fnHeaders = () => ({ 'Content-Type': 'application/json', apikey: CFG.SUPABASE_ANON_KEY || '', Authorization: 'Bearer ' + (CFG.SUPABASE_ANON_KEY || '') });

  async function getJson(u) { const r = await fetch(u, { cache: 'no-store' }); if (!r.ok) throw new Error('http_' + r.status); return r.json(); }

  async function loadBrand() {
    try { BRAND = await getJson('/assets/brand.json'); } catch (e) { BRAND = {}; }
    document.querySelectorAll('[data-brand]').forEach(el => { const v = BRAND[el.dataset.brand]; if (typeof v === 'string' && v) el.textContent = v; });
    if (BRAND.name) document.title = 'Your fixed quote · ' + BRAND.name;
    const sup = BRAND.support_email ? ' · <a href="mailto:' + esc(BRAND.support_email) + '">' + esc(BRAND.support_email) + '</a>' : '';
    $('#footer').innerHTML = '<div class="footer__legal"><span>' + esc(BRAND.name || '') + '</span>' +
      '<a href="/legal/terms/">Terms</a><a href="/legal/privacy/">Privacy</a><a href="/legal/service-agreement/">Service Agreement</a>' +
      '<span>' + esc((BRAND.disclaimers && BRAND.disclaimers.footer) || '') + sup + '</span></div>';
    const ga = BRAND.analytics && BRAND.analytics.ga4_id;
    if (ga && !window.gtag) {
      window.dataLayer = window.dataLayer || []; window.gtag = function () { window.dataLayer.push(arguments); };
      window.gtag('js', new Date()); window.gtag('config', ga, { page_location: cleanUrl, page_referrer: '' });
      const s = document.createElement('script'); s.async = true; s.src = 'https://www.googletagmanager.com/gtag/js?id=' + encodeURIComponent(ga); document.head.appendChild(s);
    }
  }
  // funnel event names live only in brand.json analytics.events; the name is assembled from parts
  function track(parts) {
    const n = parts.join('_');
    try { if (window.gtag && ((BRAND.analytics && BRAND.analytics.events) || []).indexOf(n) !== -1) window.gtag('event', n); } catch (e) { /* never breaks the page */ }
  }

  // ---- mock adapter: reads/writes the shared mock DB; view + accept rules come from the server's own module
  const MOCK_KEY = 'aplp_mock_db_v1';
  const mockDb = () => { try { return JSON.parse(localStorage.getItem(MOCK_KEY) || 'null') || {}; } catch (e) { return {}; } };
  const mockSave = db => { try { localStorage.setItem(MOCK_KEY, JSON.stringify(db)); } catch (e) { /* storage blocked */ } };
  let QV = null, PB = null;
  async function mockDeps() {
    if (!QV) { QV = await import('/assets/quote_view.mjs'); PB = await getJson('/assets/pricebook.json'); }
  }
  const mockId = () => (window.crypto && crypto.randomUUID) ? crypto.randomUUID() : String(Date.now()) + Math.random().toString(16).slice(2);
  function mockFind(db) {
    const q = (db.quotes || []).find(x => x.public_token === token);
    if (!QV.TOKEN_RX.test(token) || !QV.isPublic(q)) throw new Error('not_found');
    return q;
  }
  const mockProfile = (db, q) => (db.profiles || []).find(p => p.id === q.user_id) || null;
  function mockEvent(db, q, type, payload) {
    (db.events = db.events || []).push({ id: mockId(), actor: 'system', entity: 'quote', entity_id: q.id, user_id: q.user_id, type,
      payload: payload || {}, client_visible: false, created_at: new Date().toISOString() });
  }
  async function mockView() {
    await mockDeps();
    const db = mockDb(), q = mockFind(db), now = new Date();
    if (['sent', 'viewed'].includes(q.status) && QV.isExpired(q, now)) q.status = 'expired';
    else if (q.status === 'sent') { q.status = 'viewed'; q.viewed_at = q.viewed_at || now.toISOString(); }
    mockSave(db);
    return QV.toPublicView(q, mockProfile(db, q), now, PB, BRAND.agreement_version);
  }
  async function mockAccept(name) {
    await mockDeps();
    const db = mockDb(), q = mockFind(db), now = new Date();
    const chk = QV.acceptCheck(q, { name, agree: true, agreement_version: Q.agreement_version }, now, BRAND.agreement_version);
    if (chk && chk.code) throw new Error(chk.code);
    if (!chk) {
      Object.assign(q, { status: 'accepted', accepted_name: QV.normName(name), accepted_at: now.toISOString(), updated_at: now.toISOString(),
        agreement_version: q.agreement_version || BRAND.agreement_version, accepted_ip: 'mock', accepted_ua: 'mock' });
      const prof = mockProfile(db, q);
      [['quote', 'accepted'], ['admin', 'quote', 'accepted']].map(p => p.join('_')).forEach(t => {   // names joined: analytics event name is a substring
        mockEvent(db, q, 'email_requested', { template: t });
        (db.outbox = db.outbox || []).push({ id: mockId(), to: t.indexOf('admin') === 0 ? 'owner' : (prof && prof.email) || '', template: t, quote_id: q.id,
          subject: t, created_at: now.toISOString() });
      });
      mockSave(db);
    }
    return QV.toPublicView(q, mockProfile(db, q), now, PB, BRAND.agreement_version);
  }

  async function loadQuote() {
    if (fixture) return getJson('/quote/assets/fixtures/' + token + '.json');
    if (mockMode) return mockView();
    if (CFG.BACKEND !== 'supabase' || !CFG.SUPABASE_URL) throw new Error('backend_off');
    // POST with the token in the body, so it never lands in edge/proxy access logs
    const r = await fetch(fnUrl('quote-view'), { method: 'POST', headers: fnHeaders(), cache: 'no-store', body: JSON.stringify({ t: token }) });
    if (r.status === 404) throw new Error('not_found');
    if (!r.ok) throw new Error('http_' + r.status);
    return r.json();
  }

  function callLink(label) {
    const href = BRAND.calendly_url || (BRAND.support_email ? 'mailto:' + BRAND.support_email + '?subject=' + encodeURIComponent('Question about my quote') : '');
    if (!href) return '';
    const ext = /^https:/.test(href) ? ' target="_blank" rel="noopener"' : '';
    return '<a href="' + esc(href) + '"' + ext + '>' + esc(label) + '</a>';
  }

  function linesHtml(q) {
    const t = q.totals;
    const row = (name, sub, setup, monthly, cls) => '<div role="listitem" class="q-line' + (cls ? ' ' + cls : '') + '"><div class="q-line__name">' + name + (sub ? '<small>' + sub + '</small>' : '') + '</div>' +
      '<div class="q-line__amt">' + [setup, monthly].filter(Boolean).join('<br>') + '</div></div>';
    let h = q.items.map(i => row(esc(i.name) + (i.qty > 1 ? ' × ' + i.qty : ''), esc(i.code),
      i.setup_cents ? '<b>' + money(i.setup_cents) + '</b> setup' : (i.monthly_cents ? '' : 'Included'),
      i.monthly_cents ? money(i.monthly_cents) + '/mo' : '')).join('');
    if (t.discount_cents) h += row(esc(t.discount_label || 'Discount'), '', '−' + money(t.discount_cents), '', 'q-line--minus');
    h += row('Setup total', 'one time', '<b>' + money(t.setup_cents) + '</b>', '', 'q-line--total');
    h += row('Monthly total', 'from go-live', '<b>' + money(t.monthly_cents) + '/mo</b>', '', 'q-line--total');
    return '<div class="q-lines" role="list" aria-label="Price lines">' + h + '</div>' +
      '<div class="q-sched">' +
      '<div><span>Deposit to start (' + esc(t.deposit_pct) + '%)</span><b class="num">' + money(t.deposit_cents) + '</b></div>' +
      '<div><span>Before go-live</span><b class="num">' + money(t.final_cents) + '</b></div>' +
      '<div><span>Monthly, from go-live</span><b class="num">' + money(t.monthly_cents) + '</b></div></div>' +
      '<p class="muted small" style="margin-top:12px">Monthly fees start on your go-live date and are billed monthly in advance. Cancel anytime with ' + esc(q.cancel_notice_days) + ' days notice.</p>';
  }

  function inclHtml(q) {
    const inc = q.includes.map(g => '<div class="card"><h3>' + esc(g.name) + '</h3><ul class="price-card__list">' +
      g.list.map(x => '<li>' + esc(x) + '</li>').join('') + '</ul></div>').join('');
    const exc = q.excludes.length || q.not_included_extra.length ? '<div class="card"><h3>Not included</h3><ul class="price-card__list price-card__list--no">' +
      q.excludes.map(x => '<li>' + esc(x) + '</li>').join('') + q.not_included_extra.map(x => '<li>' + esc(x) + '</li>').join('') + '</ul></div>' : '';
    return '<div class="q-incl">' + inc + exc + '</div>';
  }

  function paySlot(q) {
    const dep = money(q.totals.deposit_cents);
    if (q.payment && q.payment.link) {
      return '<a class="btn btn--primary btn--block" href="' + esc(q.payment.link) + '" target="_blank" rel="noopener">Pay deposit ' + dep + '</a>' +
        '<p class="muted small">Secure payment page. Your setup starts when the deposit arrives.</p>';
    }
    const ep = BRAND.endpoints && BRAND.endpoints.payment;
    if (ep && /^https:/.test(ep)) return '<a class="btn btn--primary btn--block" href="' + esc(ep) + '" target="_blank" rel="noopener">Pay deposit ' + dep + '</a>';
    return '<div class="notice notice--ok" role="status">We’ll email your secure payment link for the ' + dep + ' deposit ' + esc(BRAND.quote_sla_text || 'soon') + '.</div>';
  }

  function acceptHtml(q) {
    if (q.status === 'accepted') {
      return '<div class="q-accept" id="accept"><div class="q-signed"><span class="badge badge--ok">Accepted</span>' +
        '<h2>Thank you, ' + esc(q.accepted.name.split(' ')[0]) + '.</h2>' +
        '<p>Accepted by <b>' + esc(q.accepted.name) + '</b> on ' + esc(fmtDate(q.accepted.at)) + ' under Service Agreement version ' + esc(q.agreement_version) + '.</p></div>' +
        '<div id="pay-slot">' + paySlot(q) + '</div></div>';
    }
    if (q.status === 'expired') {
      return '<div class="notice notice--err" id="accept" role="status">This quote expired on ' + esc(fmtDate(q.valid_until)) + '. ' +
        'Reply to your quote email' + (BRAND.support_email ? ' or write to <a href="mailto:' + esc(BRAND.support_email) + '">' + esc(BRAND.support_email) + '</a>' : '') +
        ' and we’ll send you a fresh one.</div>';
    }
    return '<form class="q-accept" id="acceptForm" novalidate><h2 id="accept">Accept your quote</h2>' +
      '<p class="small muted" style="margin-bottom:16px">Type your full name and tick the box. This is your electronic signature. We save the time you signed and a unique code that shows which exact terms you agreed to.</p>' +
      '<div class="field"><label for="accName">Full name</label><input class="input" id="accName" name="name" autocomplete="name" maxlength="200" required value="' + esc(q.client.name) + '"></div>' +
      '<label class="check" style="margin-bottom:16px"><input type="checkbox" id="accAgree" required><span>I agree to the <a href="/legal/service-agreement/" target="_blank" rel="noopener">Service Agreement v' + esc(q.agreement_version) + '</a>, the <a href="/legal/terms/" target="_blank" rel="noopener">Terms of Service</a> and this quote, including individual arbitration, the class-action waiver and the 30-day opt-out (Terms §17), and I’m authorized to sign for ' + esc(q.client.company || 'my business') + ' and buying for its business use.</span></label>' +
      '<div id="accMsg"></div>' +
      '<button class="btn btn--primary btn--block" type="submit" id="accBtn">Accept &amp; pay deposit ' + money(q.totals.deposit_cents) + '</button>' +
      '<div id="pay-slot" hidden></div></form>';
  }

  function render(q) {
    Q = q;
    const t = q.totals;
    const status = q.status === 'accepted' ? '<span class="badge badge--ok">Accepted</span>' : q.status === 'expired' ? '<span class="badge">Expired</span>' : '<span class="badge badge--acc">Fixed price</span>';
    const call = callLink('Prefer a quick 15-min video call?');
    const callBlock = call && q.status === 'open' ? (q.call_offer_prominent
      ? '<div class="notice q-call q-noprint" style="margin-bottom:24px"><span>Bigger project, so a short call can help. ' + call + ' It’s optional — you can accept online anytime.</span></div>'
      : '<p class="q-call">' + call + '</p>') : '';
    const days = q.delivery_business_days ? '<p><b>' + esc(q.delivery_business_days) + ' business days</b> to deliver, counted from when your setup checklist is complete.</p>' : '';
    const refund = (q.refund.guarantee ? '<p><b>' + esc(q.refund.guarantee) + '</b></p>' : '') + '<p>' + esc(q.refund.deposit) + '</p>' + (q.refund.retainer ? '<p>' + esc(q.refund.retainer) + '</p>' : '');
    $('#app').innerHTML =
      '<div class="q-head"><span class="eyebrow">Fixed quote' + (q.client.company ? ' · ' + esc(q.client.company) : '') + '</span>' +
      '<h1>' + (q.client.company ? 'Your quote, ' + esc(q.client.company) : 'Your fixed quote') + '</h1>' +
      '<div class="q-meta">' + status + (q.valid_until ? '<span>Valid until ' + esc(fmtDate(q.valid_until)) + '</span>' : '') +
      (q.client.name ? '<span>Prepared for ' + esc(q.client.name) + '</span>' : '') + '</div>' +
      '<p class="q-printurl">' + esc(cleanUrl) + '</p></div>' +
      callBlock +
      '<div class="q-layout"><div class="q-main">' +
      '<section aria-labelledby="h-scope"><h2 id="h-scope">What we’ll build</h2><div class="q-prose">' + md(q.scope_md) + '</div></section>' +
      '<section aria-labelledby="h-price"><h2 id="h-price">Price</h2>' + linesHtml(q) + '</section>' +
      '<section aria-labelledby="h-incl"><h2 id="h-incl">What’s included</h2>' + inclHtml(q) + '</section>' +
      (q.assumptions.length ? '<section aria-labelledby="h-ass"><h2 id="h-ass">Assumptions</h2><ul class="q-list">' + q.assumptions.map(a => '<li>' + esc(a) + '</li>').join('') + '</ul></section>' : '') +
      '<section aria-labelledby="h-time"><h2 id="h-time">Timeline</h2><div class="q-prose">' + days + md(q.timeline_text) + '</div></section>' +
      '<section aria-labelledby="h-refund"><h2 id="h-refund">Refunds</h2><div class="q-prose">' + refund + '</div></section>' +
      '<section aria-label="Accept">' + acceptHtml(q) + '</section>' +
      '</div>' +
      '<aside class="q-aside" aria-label="Summary"><div class="price-card price-card--featured q-sum">' +
      '<span class="eyebrow">Setup, one time</span><div class="price-card__amount"><b>' + money(t.setup_cents) + '</b><span>+ ' + money(t.monthly_cents) + '/mo from go-live</span></div>' +
      '<dl><dt>Deposit to start</dt><dd>' + money(t.deposit_cents) + '</dd><dt>Before go-live</dt><dd>' + money(t.final_cents) + '</dd>' +
      (t.discount_cents ? '<dt>' + esc(t.discount_label || 'Discount') + '</dt><dd>−' + money(t.discount_cents) + '</dd>' : '') + '</dl>' +
      (q.status === 'open' ? '<a class="btn btn--primary btn--block q-noprint" href="#accept">Accept &amp; pay deposit</a>' : '') +
      (call && q.status === 'open' ? '<p class="q-call small">' + call + '</p>' : '') +
      '<p class="price-card__fine">Prices in ' + esc(q.currency || 'USD') + '. ' + (q.valid_until && q.status === 'open' ? 'Valid until ' + esc(fmtDate(q.valid_until)) + '.' : '') + '</p>' +
      '</div></aside></div>';
    const f = $('#acceptForm');
    if (f) f.addEventListener('submit', onAccept);
  }

  async function onAccept(ev) {
    ev.preventDefault();
    const name = $('#accName').value.replace(/\s+/g, ' ').trim();
    const agree = $('#accAgree').checked;
    const msg = $('#accMsg');
    const say = (t, k) => { msg.innerHTML = '<div class="notice notice--' + (k || 'err') + '" role="alert" style="margin-bottom:14px">' + esc(t) + '</div>'; };
    if (name.length < 2) { say('Please type your full name.'); $('#accName').focus(); return; }
    if (!agree) { say('Please tick the box to agree to the Service Agreement.'); $('#accAgree').focus(); return; }
    const btn = $('#accBtn'); btn.disabled = true; btn.textContent = 'Saving…';
    try {
      let q;
      if (fixture) {
        q = Object.assign({}, Q, { status: 'accepted', accepted: { name, at: new Date().toISOString() } });
      } else if (mockMode) {
        q = await mockAccept(name);
      } else {
        const r = await fetch(fnUrl('quote-accept'), { method: 'POST', headers: fnHeaders(),
          body: JSON.stringify({ t: token, name, agree: true, agreement_version: Q.agreement_version }) });
        const j = await r.json().catch(() => ({}));
        if (!r.ok) throw new Error(j.error || 'http_' + r.status);
        q = j;
      }
      track(['quote', 'accept']);
      render(q);
      const slot = $('#accept'); if (slot) slot.scrollIntoView({ block: 'start' });
    } catch (e) {
      const m = String(e && e.message || e);
      say(/expired/.test(m) ? 'This quote has expired. Contact us and we’ll send a fresh one.'
        : /already_accepted/.test(m) ? 'This quote was already accepted. Reload the page to see it.'
        : /agreement_version/.test(m) ? 'The agreement was updated. Reload the page and review it again.'
        : /Failed to fetch|NetworkError/.test(m) ? 'Can’t reach the server. Check your connection and try again.'
        : 'Something went wrong. Please try again, or reply to your quote email.');
      btn.disabled = false; btn.innerHTML = 'Accept &amp; pay deposit ' + money(Q.totals.deposit_cents);
    }
  }

  function fail(code) {
    const sup = BRAND.support_email ? ' Write to <a href="mailto:' + esc(BRAND.support_email) + '">' + esc(BRAND.support_email) + '</a> and we’ll help.' : '';
    const text = code === 'backend_off' ? 'Quotes open here soon.' : 'We couldn’t find this quote. The link may be incomplete, or the quote was replaced by a newer one.';
    $('#app').innerHTML = '<div class="q-head"><span class="eyebrow">Fixed quote</span><h1>Quote not found</h1><p class="lead">' + esc(text) + sup + '</p></div>';
  }

  document.addEventListener('DOMContentLoaded', () => {
    const p = $('#printBtn'); if (p) p.addEventListener('click', () => window.print());
  });
  (async function init() {
    await loadBrand();
    if (!token) return fail('not_found');
    try { render(await loadQuote()); } catch (e) { fail(String(e && e.message || e)); }
  })();
})();
